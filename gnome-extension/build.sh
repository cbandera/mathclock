#!/usr/bin/env bash
# Builds the extension zip. With --install, also installs it for the current user.
#   ./build.sh            -> dist/mathclock@cbandera.github.io.shell-extension.zip
#   ./build.sh --install  -> build + gnome-extensions install --force
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
uuid="mathclock@cbandera.github.io"

# Wrap the shared browser/Node generator as an ES module for GNOME Shell.
{
  echo '// GENERATED by build.sh from ../web/riddle.js. Edit that file instead.'
  echo 'const module = {exports: {}};'
  cat "$here/../web/riddle.js"
  echo 'export default module.exports;'
} > "$here/riddle.js"

mkdir -p "$here/dist"
gnome-extensions pack "$here" --force --out-dir="$here/dist" --extra-source=riddle.js
echo "Built $here/dist/$uuid.shell-extension.zip"

if [[ "${1:-}" == "--install" ]]; then
  gnome-extensions install --force "$here/dist/$uuid.shell-extension.zip"
  echo "Installed. Log out and back in, then run: gnome-extensions enable $uuid"
fi
